import os
import sys
import configparser

config = configparser.ConfigParser()
config.optionxform = str

ini_file, out_file = sys.argv[1], sys.argv[2]
config.read(ini_file)

with open(out_file, "w") as f:
    f.write(f"// AUTOGENERATED by {os.path.basename(sys.argv[0])} from {os.path.basename(ini_file)} -- do not edit.\n")
    f.write("#pragma once\n\n")
    for name, value in config["Counters"].items():
        flag = "true" if value.lower() == "on" else "false"
        f.write(f"inline constexpr bool COUNTER_{name} = {flag};\n")
